"""Build the OrcaSlicer plugin as a pure-Python wheel: dist/orca_print_calculator_any.whl.

Runs the UI build, inlines ui/dist/index.html and ui/src/icon.svg into the generated
src/orca_print_calculator/_assets.py, then zips the package with hand-written dist-info.
Zip timestamps are fixed so equal sources give equal bytes.
"""

import argparse
import ast
import base64
import hashlib
import re
import shutil
import subprocess
import tomllib
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = "orca_print_calculator"
SRC = ROOT / "src" / PKG
UI = ROOT / "ui"
MODULES = ("core", "host")


def clean_svg(text):
    """Strip prolog/comments/ids and refuse anything scriptable."""
    text = re.sub(r"<\?xml.*?\?>|<!--.*?-->|\s+id=\"[^\"]*\"", "", text, flags=re.S)
    text = re.sub(r">\s+<", "><", text).strip()
    if re.search(r"<script|\bon\w+\s*=|javascript:", text, flags=re.I):
        raise SystemExit("icon.svg: scriptable content")
    return text


def build_ui():
    icon = UI / "src" / "icon.svg"
    if not icon.is_file():
        raise SystemExit("missing %s (the tab icon is authored separately; build cannot continue)" % icon.relative_to(ROOT))
    pnpm = shutil.which("pnpm")
    if not pnpm:
        raise SystemExit("pnpm not found on PATH")
    subprocess.run([pnpm, "-C", str(UI), "install", "--frozen-lockfile"], check=True)
    subprocess.run([pnpm, "-C", str(UI), "build"], check=True)
    index = UI / "dist" / "index.html"
    if not index.is_file():
        raise SystemExit("ui build produced no %s" % index.relative_to(ROOT))
    return index.read_text("utf-8"), clean_svg(icon.read_text("utf-8"))


def write_assets(html, svg):
    (SRC / "_assets.py").write_text(
        "# Generated by scripts/build.py. Do not edit.\nAPP_HTML = %r\nICON_SVG = %r\n" % (html, svg), "utf-8")


def wheel_files(project):
    plugin = (SRC / "__init__.py").read_text("utf-8")
    if plugin.count('VERSION = "0.0.0-dev"') != 1:
        raise SystemExit("__init__.py must contain exactly one VERSION placeholder")
    sources = {
        "__init__": plugin.replace('VERSION = "0.0.0-dev"', "VERSION = %r" % project["version"]),
        "_assets": (SRC / "_assets.py").read_text("utf-8"),
        **{m: (SRC / (m + ".py")).read_text("utf-8") for m in MODULES},
    }
    files = {}
    for name, text in sources.items():
        ast.parse(text, name + ".py")  # syntax check only
        files["%s/%s.py" % (PKG, name)] = text.encode("utf-8")
    return files


def dist_info(project, files):
    dist_name = project["name"].replace("-", "_")
    di = "%s-%s.dist-info/" % (dist_name, project["version"])
    meta = {
        di + "METADATA": "\n".join([
            "Metadata-Version: 2.1",
            "Name: " + project["name"],
            "Version: " + project["version"],
            "Summary: " + project["description"],
            "Author: " + project["authors"][0]["name"],
            "License: " + project["license"],
            "Requires-Python: " + project["requires-python"],
            "",
        ]),
        di + "WHEEL": "Wheel-Version: 1.0\nGenerator: orca-print-calculator scripts/build.py\nRoot-Is-Purelib: true\nTag: py3-none-any\n",
        di + "top_level.txt": PKG + "\n",
    }
    meta = {k: v.encode("utf-8") for k, v in meta.items()}
    record = []
    for path, data in {**files, **meta}.items():
        digest = base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=").decode()
        record.append("%s,sha256=%s,%d" % (path, digest, len(data)))
    record.append(di + "RECORD,,")
    meta[di + "RECORD"] = ("\n".join(record) + "\n").encode("utf-8")
    return meta


def build(out_dir=ROOT / "dist", release_tag=None):
    project = tomllib.loads((ROOT / "pyproject.toml").read_text("utf-8"))["project"]
    if release_tag is not None and release_tag.lstrip("v") != project["version"]:
        raise SystemExit("tag %s does not match version %s" % (release_tag, project["version"]))
    write_assets(*build_ui())
    files = wheel_files(project)
    files.update(dist_info(project, files))
    out_dir.mkdir(parents=True, exist_ok=True)
    artifact = out_dir / (PKG + "_any.whl")
    with zipfile.ZipFile(artifact, "w", zipfile.ZIP_DEFLATED) as z:
        for path, data in files.items():
            info = zipfile.ZipInfo(path, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, data)
    digest = hashlib.sha256(artifact.read_bytes()).hexdigest()
    (out_dir / "SHA256SUMS").write_text("%s  %s\n" % (digest, artifact.name), "utf-8")
    return artifact


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--release-tag")
    print(build(release_tag=parser.parse_args().release_tag))
