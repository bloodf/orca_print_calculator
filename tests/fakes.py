"""Fake `orca` module for host tests. Every `orca.host` call must happen on the "UI thread"
(the test's main thread); a call from any other thread is recorded in `orca.violations` and raises."""

import enum
import importlib
import sys
import tempfile
import threading
import types
from pathlib import Path


class LifecycleEvent(enum.Enum):
    NewProject = 1
    ProjectOpened = 2
    ProjectClosed = 3
    GCodeExportFinished = 4
    SlicingJobComplete = 5
    ObjectAdded = 6
    ObjectDeleted = 7
    ObjectTransformed = 8
    ObjectChanged = 9
    PlateDeleted = 10
    PresetSelected = 11
    PresetSaved = 12
    PlateSelected = 13
    PlateCreated = 14
    SliceStarted = 15


class LifecycleEvtCode(enum.Enum):
    Ok = 0
    Error = 1
    Warn = 2


def ctx(msg="", name="", index=-1, code=LifecycleEvtCode.Ok):
    return types.SimpleNamespace(msg=msg, name=name, previous_name="", index=index, code=code)


class Preset:
    def __init__(self, name, cfg):
        self.name, self.cfg = name, cfg

    def config_value(self, key):
        return self.cfg.get(key)


def install_orca(storage=None):
    """Register a fake `orca` in sys.modules and return it. `orca.state` drives what the host sees."""
    orca = types.ModuleType("orca")
    orca.violations = []
    orca.registered = []
    orca.permissions = []
    orca.state = {
        "plate": 0,
        "project": "/Users/x/Projects/Desk organizer.3mf",
        "printer": {"printer_model": "Snapmaker U1", "printer_vendor": "Snapmaker"},
        "printer_name": "Snapmaker U1 (0.4 nozzle)",
        "filaments": [Preset("Generic PLA @U1", {"filament_cost": "24", "filament_notes": "", "filament_type": "PLA"}),
                      Preset("Generic PETG (#12)", {"filament_cost": "30", "filament_notes": "Spoolman filament 12",
                                                    "filament_type": "PETG"})],
        "colours": "#E8E8E8;#2E6FBF",
    }
    if storage is None:
        root = Path(tempfile.mkdtemp())
        storage = root / "OrcaSlicer" / "orca_plugins" / "plugin_data" / "orca_print_calculator"
        storage.mkdir(parents=True)
    orca.storage_dir = str(storage)

    def ui(fn):
        def wrapper(*a, **k):
            if threading.current_thread() is not threading.main_thread():
                orca.violations.append(fn.__name__)
                raise RuntimeError("%s() must be called from the UI thread" % fn.__name__)
            return fn(*a, **k)
        wrapper.__name__ = fn.__name__
        return wrapper

    class Base:
        def __init__(self):
            self.posted = []
            self.posted_cv = threading.Condition()

        def post_message(self, data):  # callable from any thread, like the real host
            with self.posted_cv:
                self.posted.append(data)
                self.posted_cv.notify_all()

        def wait_for(self, pred, timeout=5):
            """Block until `pred(posted)` is true (event-driven, no sleep polling); returns its value."""
            with self.posted_cv:
                return self.posted_cv.wait_for(lambda: pred(self.posted), timeout)

    @ui
    def storage_fn():
        return orca.storage_dir

    @ui
    def preset_bundle():
        st = orca.state
        return types.SimpleNamespace(
            current_printer_preset=lambda: Preset(st["printer_name"], st["printer"]),
            current_filament_presets=lambda: list(st["filaments"]),
            full_config_value=lambda k: st["colours"] if k == "filament_colour" else st["printer"].get(k))

    @ui
    def model():
        return types.SimpleNamespace(current_plate_index=lambda: orca.state["plate"])

    @ui
    def plater():
        return types.SimpleNamespace(project_path=lambda: orca.state["project"])

    orca.pages = types.SimpleNamespace(PagesPluginCapabilityBase=Base)
    orca.PluginType = types.SimpleNamespace(Pages="Pages")
    orca.LifecycleEvent = LifecycleEvent
    orca.LifecycleEvtCode = LifecycleEvtCode
    orca.base = object
    orca.plugin = lambda cls: cls
    orca.register_capability = orca.registered.append
    orca.request_permissions = lambda **kw: orca.permissions.append(kw)
    orca.host = types.SimpleNamespace(plugin=types.SimpleNamespace(storage=storage_fn), preset_bundle=preset_bundle,
                                      model=model, plater=plater)
    sys.modules["orca"] = orca
    return orca


def load_plugin(path):
    """Import package `orca_print_calculator` fresh from `path` (src dir or extracted wheel). Call after install_orca().
    `_assets.py` is generated by scripts/build.py (gitignored); on a clean checkout a stub stands in for it."""
    for name in [n for n in sys.modules if n == "orca_print_calculator" or n.startswith("orca_print_calculator.")]:
        del sys.modules[name]
    if not (Path(path) / "orca_print_calculator" / "_assets.py").is_file():
        stub = types.ModuleType("orca_print_calculator._assets")
        stub.APP_HTML, stub.ICON_SVG = "<!doctype html><title>stub</title>", "<svg/>"
        sys.modules[stub.__name__] = stub
    sys.path[:] = [p for p in sys.path if p != str(path)]
    sys.path.insert(0, str(path))
    importlib.invalidate_caches()
    return importlib.import_module("orca_print_calculator")
